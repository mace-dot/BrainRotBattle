return function(test,eq,Config)
    local Movement=dofile("src/server/BattleServer/MovementState.luau")
    local function fresh() local m=Movement.new(Config); m:reset(1); return m,m.Players[1] end
    test("sprint lasts five seconds, exhaustion recharges in twenty",function()
        local m,s=fresh(); assert(m:request(1,"SprintOn",function() return true end,true)); eq(m:speed(1),30)
        for _=1,50 do m:step(1,0.1,true,true,false) end
        eq(s.Stamina,0); eq(s.Sprint,false); eq(s.Exhausted,true)
        eq(m:request(1,"SprintOn",function() return true end,true),false)
        m:step(1,3.9,false,true,false); eq(s.Exhausted,true)
        m:step(1,0.1,false,true,false); eq(s.Exhausted,false)
        m:step(1,16,false,true,false); assert(math.abs(s.Stamina-1)<0.000001)
    end)
    test("stationary sprint does not drain stamina",function()
        local m,s=fresh(); m:request(1,"SprintOn",function() return true end,true)
        m:step(1,10,false,true,false); eq(s.Stamina,1)
    end)
    test("stances exclude sprint and cannot stand through a ceiling",function()
        local m,s=fresh(); assert(m:request(1,"Crouch",function() return true end,true)); eq(m:speed(1),12)
        eq(m:request(1,"SprintOn",function() return true end,true),false)
        eq(m:request(1,"Crouch",function() return false end,true),false); eq(s.Stance,"Crouch")
        assert(m:request(1,"Prone",function() return true end,true)); eq(m:speed(1),6)
        assert(m:request(1,"Prone",function() return true end,true)); eq(s.Stance,"Stand")
    end)
    test("airborne transitions reject, falling reload and firing stop sprint",function()
        local m,s=fresh(); eq(m:request(1,"Prone",function() return true end,false),false)
        m:request(1,"SprintOn",function() return true end,true); m:step(1,0.1,true,false,false); eq(s.Sprint,false)
        m:request(1,"SprintOn",function() return true end,true); m:step(1,0.1,true,true,true); eq(s.Sprint,false)
        m:request(1,"SprintOn",function() return true end,true); m:stop(1); eq(s.Sprint,false)
        m:remove(1); eq(m:request(1,"SprintOn",function() return true end,true),false)
        m:reset(1); eq(m.Players[1].Stance,"Stand"); eq(m.Players[1].Stamina,1)
    end)
end
